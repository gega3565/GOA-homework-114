# 2) მომხმარებელს შემოაყვანინეთ მთელი რიცხვი n.
#  შემდეგ while ციკლის გამოყენებით გამოიტანეთ რიცხვები 1-იდან n-ის ჩათვლით.
# მოიძიეთ ინფორმაცია და გამოიყენეთ if და else, რათა:
# თუ რიცხვი ლუწია, ტერმინალში გამოიტანოთ "Even";
# სხვა შემთხვევაში გამოიტანოთ "Odd"

n = int(input("enter a whole number: "))

i = 1
while i <= n:
    if i % 2 == 0:
        print(i, "even")
    else:
        print(i, "odd")
    i += 1

# if - ამოწმებს პირობას. თუ პირობა ჭეშმარიტია მის ქვეშ დაწერილი კოდი სრულდება.
# else - სრულდება როცა if მცდარია.
