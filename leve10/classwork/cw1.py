# ყვცელა ის რიცხვი 1-დან n-ის ჩავლით რომელიც 3-ზე უნაშთოდ იყოფა.
# საბოლოოდ გამოიტანეთ მიღებული ჯამი

n = int(input("enter a whole number: "))

total = 0

for num in range(1, n + 1):
    if num % 3 == 0:
        total += num

print(total)








