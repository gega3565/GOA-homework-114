#3) მომხმარებელს შემოაყვანინეთ რიცხვი n და დათვალეთ,
#  რამდენი რიცხვია 1-იდან n-ის ჩათვლით,
#  რომელიც 3-ის ჯერადია.
#  საბოლოოდ გამოიტანეთ ამ რიცხვების რაოდენობა.
#  ეს დავალება შეასრულეთ როგორც for, ასევე while ციკლით.


n = int(input("შეიყვანეთ n: "))


count = 0
for i in range(3, n + 1, 3):
    count = count + 1
print(count)


count = 0
i = 3
while i <= n:
    count = count + 1
    i = i + 3
print(count)



