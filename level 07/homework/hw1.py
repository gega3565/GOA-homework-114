# 2) მომხმარებელს შემოაყვანინეთ რიცხვი n და ტერმინალში გამოიტანეთ რიცხვები 1-იდან n-ის ჩათვლით.
# ეს დავალება შეასრულეთ როგორც for,
# ასევე მოიძიეთ ინფორმაცია while ციკლზე და while loop-ითაც შეარსრულეთ ეს დავალება.

n = int(input("input n: "))

for i in range (1, n + 1):
    print(i)


i = 1
while i <= n:
    print(i)
    i = i + 1



# while - ციკლი იმეორებს კოდის ბლოკს მანამ, სანამ პირობა სრულდება. როგორც კი პირობა False გახდება, ციკლი ჩერდება.