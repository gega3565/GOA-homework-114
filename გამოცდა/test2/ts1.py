# 1) შექმენი ოთხი ფუნქცია add, subtract, divide და multiply,
#  შენი დავალებაა რომ ამ ფუნქციებმა შეასრულონ შესაბამისი მათემატიკური ოპერაციები და
#  დააბრუნონ შედეგები (დამატება, გამოკლება, გაყოფა და გამრავლება),
#  ოთხივე ფუნქციას არგუმენტად უნდა გადაეცემოდეს ორი რიცხვი.

def add(a, b):
    return a + b

def subtract(a, b):
    return a - b

def divide(a, b):
    return a // b

def multiply(a, b):
    return a * b

print(add(4, 8))
print(subtract(8, 6))
print(divide(88, 11))
print(multiply(128, 4))




