# 4) შექმენით ფუნქცია check_even(), რომელსაც გადაეცემა ერთი რიცხვი.
#  ფუნქციამ შეამოწმოს, არის თუ არა რიცხვი ლუწი. თუ ლუწია,
#  დააბრუნოს ტექსტი „ლუწი რიცხვია“, ხოლო სხვა შემთხვევაში — „კენტი რიცხვია“.

def check_even(number):
    if number % 2 == 0:
        return "ლუწი რიცხვია"
    else:
        return "კენტი რიცხვია"

print(check_even(4))
print(check_even(7))
